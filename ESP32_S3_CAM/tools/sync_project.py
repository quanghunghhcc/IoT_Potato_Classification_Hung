"""Synchronise the Arduino sketches with the trained model and with each other.

1. Verifies models/potato_model_data.h contains exactly the bytes of models/potato_int8.tflite.
2. Verifies class order in models/potato_metadata.json == CLASSES in train.py.
3. Copies models/potato_model_data.h VERBATIM into the main sketch and generates model_data.h
   (extern declarations + expected size/CRC32/quantization from the real files).
4. Copies the shared module files from the main sketch (master copy) into every example sketch,
   so each example is a self-contained Arduino sketch (no relative includes).

    .venv\\Scripts\\python.exe ESP32_S3_CAM\\tools\\sync_project.py           # write
    .venv\\Scripts\\python.exe ESP32_S3_CAM\\tools\\sync_project.py --check   # verify only (exit 1 on drift)

Edit shared code ONLY in Potato_Classifier_ESP32S3/, then run this script.
"""

import argparse
import ast
import hashlib
import json
import re
import sys
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
FW = HERE.parent
ROOT = FW.parent
MAIN = FW / "Potato_Classifier_ESP32S3"
EX = FW / "examples"

SHARED = {
    "02_Test_Sensor": ["config.h", "board_pins.h", "sensor_module.h", "sensor_module.cpp"],
    "03_Test_Camera": ["config.h", "board_pins.h", "camera_module.h", "camera_module.cpp",
                       "image_preprocessing.h", "image_preprocessing.cpp", "diagnostics.h", "diagnostics.cpp"],
    "04_Test_LEDs": ["config.h", "board_pins.h", "led_control.h", "led_control.cpp"],
    "05_Test_CNN": ["config.h", "cnn_inference.h", "cnn_inference.cpp", "image_preprocessing.h",
                    "image_preprocessing.cpp", "diagnostics.h", "diagnostics.cpp", "model_data.h",
                    "model_data.cpp", "potato_model_data.h"],
    "06_Full_System_Test": ["config.h", "board_pins.h", "camera_module.h", "camera_module.cpp",
                            "cnn_inference.h", "cnn_inference.cpp", "diagnostics.h", "diagnostics.cpp",
                            "image_preprocessing.h", "image_preprocessing.cpp", "led_control.h",
                            "led_control.cpp", "model_data.h", "model_data.cpp", "potato_model_data.h",
                            "network_reporter.h", "network_reporter.cpp", "secrets.example.h",
                            "sensor_module.h", "sensor_module.cpp", "system_controller.h",
                            "system_controller.cpp"],
}
# Copied only when present (secrets.h is git-ignored and user-specific).
OPTIONAL = {"06_Full_System_Test": ["secrets.h"]}


def header_bytes(text):
    body = text[text.index("{") + 1: text.index("};")]
    return bytes(int(h, 16) for h in re.findall(r"0x([0-9a-fA-F]{2})", body))


def train_classes():
    tree = ast.parse((ROOT / "train.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "CLASSES" for t in node.targets):
            return list(ast.literal_eval(node.value))
    raise RuntimeError("CLASSES not found in train.py")


def model_data_h(blob, meta):
    inp, out = meta["tflite_test"]["input"], meta["tflite_test"]["output"]
    _, h, w, c = inp["shape"]
    names = meta["class_names"]
    return f"""// model_data.h — GENERATED by tools/sync_project.py from models/potato_int8.tflite and
// models/potato_metadata.json. Do not edit by hand; re-run the tool after retraining.
#pragma once

// Định nghĩa thật nằm trong model_data.cpp (include potato_model_data.h đúng MỘT lần).
extern const unsigned char g_potato_model[];
extern const unsigned int g_potato_model_len;

#define POTATO_MODEL_EXPECTED_LEN {len(blob)}u
#define POTATO_MODEL_EXPECTED_CRC32 0x{zlib.crc32(blob):08x}u
#define POTATO_MODEL_SHA256 "{hashlib.sha256(blob).hexdigest()}"

// Thứ tự lớp: train.py CLASSES == potato_metadata.json class_names
#define POTATO_NUM_CLASSES {len(names)}
#define POTATO_CLASS_NAME_0 "{names[0]}"
#define POTATO_CLASS_NAME_1 "{names[1]}"

#define POTATO_INPUT_HEIGHT {h}
#define POTATO_INPUT_WIDTH {w}
#define POTATO_INPUT_CHANNELS {c}

// Giá trị trong potato_metadata.json — chỉ để đối chiếu; firmware dùng tham số đọc từ tensor lúc chạy.
#define POTATO_META_INPUT_SCALE {inp['scale']!r}f
#define POTATO_META_INPUT_ZERO_POINT ({inp['zero_point']})
#define POTATO_META_OUTPUT_SCALE {out['scale']!r}f
#define POTATO_META_OUTPUT_ZERO_POINT ({out['zero_point']})
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="only verify, do not write")
    a = ap.parse_args()

    blob = (ROOT / "models" / "potato_int8.tflite").read_bytes()
    src_header = (ROOT / "models" / "potato_model_data.h").read_bytes()
    meta = json.loads((ROOT / "models" / "potato_metadata.json").read_text(encoding="utf-8"))

    problems = []
    if header_bytes(src_header.decode("ascii")) != blob:
        problems.append("models/potato_model_data.h bytes != models/potato_int8.tflite")
    if meta["model_bytes"] != len(blob):
        problems.append("potato_metadata.json model_bytes != tflite size")
    if meta["class_names"] != train_classes():
        problems.append(f"class order mismatch: metadata {meta['class_names']} vs train.py {train_classes()}")
    if len(meta["class_names"]) != 2:
        problems.append("firmware expects exactly 2 classes")
    if problems:
        print("\n".join("ERROR: " + p for p in problems))
        return 1

    wanted = {MAIN / "potato_model_data.h": src_header,
              MAIN / "model_data.h": model_data_h(blob, meta).encode("utf-8")}
    for sketch, files in SHARED.items():
        for name in files:
            src = MAIN / name
            wanted[EX / sketch / name] = wanted.get(src) or src.read_bytes()
    for sketch, files in OPTIONAL.items():
        for name in files:
            if (MAIN / name).exists():
                wanted[EX / sketch / name] = (MAIN / name).read_bytes()

    drift = 0
    for path, data in wanted.items():
        current = path.read_bytes() if path.exists() else None
        if current == data:
            continue
        drift += 1
        rel = path.relative_to(FW)
        if a.check:
            print(f"OUT OF SYNC: {rel}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            print(f"updated: {rel}")
    print(f"model: {len(blob)} B, CRC32 0x{zlib.crc32(blob):08x}, classes {meta['class_names']}")
    print(f"{len(wanted)} files checked, {drift} {'out of sync' if a.check else 'written'}")
    return 1 if (a.check and drift) else 0


if __name__ == "__main__":
    sys.exit(main())
