"""Train potato CNN and export fully int8 TFLite for ESP32-S3-CAM."""

import argparse
import json
import random
from pathlib import Path


CLASSES = ("good", "not_good")
EXTENSIONS = {".jpg", ".jpeg", ".png", ".bmp"}


def arguments():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--dataset", type=Path, default=Path("dataset"))
    p.add_argument("--output", type=Path, default=Path("models"))
    p.add_argument("--image-size", type=int, default=96)
    p.add_argument("--batch-size", type=int, default=32)
    p.add_argument("--epochs", type=int, default=30)
    p.add_argument("--representative-samples", type=int, default=200)
    p.add_argument("--seed", type=int, default=42)
    return p.parse_args()


def check_dataset(root):
    counts = {}
    for split in ("train", "val", "test"):
        counts[split] = {}
        for name in CLASSES:
            folder = root / split / name
            if not folder.is_dir():
                raise FileNotFoundError(f"Missing folder: {folder}")
            n = sum(f.is_file() and f.suffix.lower() in EXTENSIONS for f in folder.iterdir())
            if not n:
                raise ValueError(f"No images in {folder}")
            counts[split][name] = n
    return counts


def dataset(tf, path, size, batch, shuffle, seed):
    return tf.keras.utils.image_dataset_from_directory(
        path, labels="inferred", label_mode="int", class_names=list(CLASSES),
        color_mode="rgb", image_size=(size, size), interpolation="bilinear",
        batch_size=batch, shuffle=shuffle, seed=seed,
    ).prefetch(tf.data.AUTOTUNE)


def cnn(tf, size):
    L = tf.keras.layers
    inputs = L.Input((size, size, 3), name="rgb888_0_to_255")
    x = L.Rescaling(1 / 255)(inputs)
    x = L.Conv2D(16, 3, padding="same", activation="relu")(x)
    x = L.MaxPooling2D()(x)
    for channels in (24, 32, 48):
        x = L.SeparableConv2D(channels, 3, padding="same", activation="relu")(x)
        x = L.MaxPooling2D()(x)
    x = L.GlobalAveragePooling2D()(x)
    x = L.Dense(24, activation="relu")(x)
    x = L.Dropout(0.2)(x)
    return tf.keras.Model(inputs, L.Dense(2, activation="softmax")(x))


def write_header(blob, path):
    lines = [
        "// Generated by train.py; include in exactly one C++ translation unit.",
        "#pragma once", "#include <cstddef>", "#include <cstdint>",
        "alignas(16) const unsigned char g_potato_model[] = {",
    ]
    for i in range(0, len(blob), 12):
        lines.append("  " + ", ".join(f"0x{v:02x}" for v in blob[i:i + 12]) + ",")
    lines += ["};", "const unsigned int g_potato_model_len = sizeof(g_potato_model);", ""]
    path.write_text("\n".join(lines), encoding="ascii")


def test_tflite(tf, blob, test):
    import numpy as np

    runner = tf.lite.Interpreter(model_content=blob)
    runner.allocate_tensors()
    inp, out = runner.get_input_details()[0], runner.get_output_details()[0]
    if inp["dtype"] != np.int8 or out["dtype"] != np.int8:
        raise RuntimeError("Expected int8 input and output tensors")
    ins, inz = inp["quantization"]
    outs, outz = out["quantization"]
    if ins <= 0 or outs <= 0:
        raise RuntimeError("Invalid quantization scales")
    correct = total = 0
    for images, labels in test:
        for image, label in zip(images.numpy(), labels.numpy()):
            value = np.clip(np.rint(image / ins + inz), -128, 127).astype(np.int8)[None]
            runner.set_tensor(inp["index"], value)
            runner.invoke()
            correct += int(np.argmax(runner.get_tensor(out["index"])[0]) == label)
            total += 1
    return {
        "accuracy": correct / total, "samples": total,
        "input": {"shape": inp["shape"].tolist(), "dtype": "int8", "scale": float(ins), "zero_point": int(inz)},
        "output": {"shape": out["shape"].tolist(), "dtype": "int8", "scale": float(outs), "zero_point": int(outz)},
    }


def main():
    a = arguments()
    if min(a.batch_size, a.epochs, a.representative_samples) < 1 or a.image_size < 32 or a.image_size % 16:
        raise ValueError("Batch size, epochs and sample count must be positive; image size must be >=32 and divisible by 16")
    counts = check_dataset(a.dataset)
    try:
        import tensorflow as tf
    except ImportError as exc:
        raise SystemExit("Install dependencies with: python -m pip install -r requirements.txt") from exc

    random.seed(a.seed)
    tf.keras.utils.set_random_seed(a.seed)
    a.output.mkdir(parents=True, exist_ok=True)
    train = dataset(tf, a.dataset / "train", a.image_size, a.batch_size, True, a.seed)
    train = train.map(
        lambda images, labels: (tf.image.random_flip_left_right(images), labels),
        num_parallel_calls=tf.data.AUTOTUNE,
    ).prefetch(tf.data.AUTOTUNE)
    val = dataset(tf, a.dataset / "val", a.image_size, a.batch_size, False, a.seed)
    test = dataset(tf, a.dataset / "test", a.image_size, a.batch_size, False, a.seed)
    model = cnn(tf, a.image_size)
    model.compile(optimizer=tf.keras.optimizers.Adam(1e-3), loss="sparse_categorical_crossentropy", metrics=["accuracy"])
    checkpoint = a.output / "potato_best.keras"
    model.fit(
        train, validation_data=val, epochs=a.epochs,
        class_weight={i: sum(counts["train"].values()) / (2 * counts["train"][name]) for i, name in enumerate(CLASSES)},
        callbacks=[
            tf.keras.callbacks.ModelCheckpoint(checkpoint, monitor="val_loss", save_best_only=True),
            tf.keras.callbacks.EarlyStopping(monitor="val_loss", patience=6, restore_best_weights=True),
        ],
    )
    model = tf.keras.models.load_model(checkpoint)
    keras_loss, keras_accuracy = model.evaluate(test)

    calibration = dataset(tf, a.dataset / "train", a.image_size, 1, True, a.seed + 1).take(a.representative_samples)

    def representative():
        for images, _ in calibration:
            yield [images.numpy()]

    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = representative
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8
    blob = converter.convert()
    result = test_tflite(tf, blob, test)
    (a.output / "potato_int8.tflite").write_bytes(blob)
    write_header(blob, a.output / "potato_model_data.h")
    metadata = {
        "class_names": list(CLASSES), "dataset_counts": counts,
        "preprocessing": "RGB888, bilinear resize, pixel values 0..255; normalization is inside model",
        "keras_test": {"loss": float(keras_loss), "accuracy": float(keras_accuracy)},
        "tflite_test": result, "model_bytes": len(blob),
    }
    (a.output / "potato_metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
